#!/usr/bin/env bash
# SPDX-License-Identifier: MPL-2.0
# Render the catalogue (AsciiDoc) from the committed census rows.
#
# Usage: render-catalogue.sh CENSUS_DIR > catalogue.adoc
#   CENSUS_DIR holds rows.jsonl (build-rows.sh), repos.jsonl,
#   private-count.json and unreachable.jsonl. Output depends on those files only, so
#   `just catalogue-check` can prove the committed catalogue is current.
set -euo pipefail
C=$1
# Read before the heredoc: a failed command inside it would not stop the run.
framed=$(jq -s length "$C/repos.jsonl")
private=$(jq -er '.private_repositories | numbers' "$C/private-count.json")
listed=$(jq -er '.listed | strings' "$C/private-count.json")
missed=$(jq -r '"* " + .repo' "$C/unreachable.jsonl")
[[ -n "$missed" ]] || missed="None."

table() { # $1 = class
  echo '[cols="3,1,1,4,1,1,1,1,1,3",options="header"]'
  echo '|==='
  echo '|Repository |Own files |Fixtures |Provers (files) |Declarations |Holes |Axioms |Unsafe |Policy |Proof-status doc'
  jq -rs --arg c "$1" '
    map(select(.class == $c))
    | sort_by(-.own_files, .repo)[]
    | "\n|https://github.com/\(.repo)[\(.repo)] |\(.own_files) |\(.fixture_files) |\(.provers) |\(.declarations) |\(.holes) |\(.axioms) |\(.unsafe) |\(.policy) |\(if .status_doc == "" then "—" else "`" + .status_doc + "`" end)"
  ' "$C/rows.jsonl"
  echo '|==='
}

cat <<EOF
// SPDX-License-Identifier: CC-BY-SA-4.0
= Estate maths catalogue
:toc:

Generated by \`scripts/census/render-catalogue.sh\` from the census of
$framed public repositories. Do not edit by hand; rerun the census.

Each row is a repository with proof files of its own, after the files the RSR
template ships as boilerplate are set aside. *Theory* and *engineering* are a
first-pass sort (more Agda/Lean/Rocq/Isabelle files than Idris2/SPARK files
reads as theory); confirm each row against PROOF-POLICY before relying on it.
Declarations are top-level names found by keyword and signature rules, so
Agda and Idris2 counts include helpers. Hole, axiom, unsafe and policy counts
come from proof-craft's \`proof-holes.sh\`: textual candidates, not kernel
verdicts.

The catalogue carries no proof status and no proof witness grade (\`PWG-\`,
PROOF-POLICY §8). Counts say what files exist, not what has been checked, and a
grade is derived from a repository's receipts, never from a census. The
*Proof-status doc* column names the file that holds those statuses, preferring
\`PROOF-STATUS\` over \`proof-debt\` over \`PROOF-NEEDS\` when a repository has more
than one.

== Theory

$(table theory)

== Engineering (APIs, ABIs, code)

$(table engineering)

== Not reached

The listing of $listed also counted $private private repositories. The census
does not read them, and this catalogue names none of them.

These public repositories could not be cloned:

$missed
EOF
