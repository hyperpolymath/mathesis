# grade-receipt.sh: the receipt of Mathesis, written and checked by the shared
# generator of PROOF-POLICY §8.5.1 (standards scripts/proof-receipt.sh).
#
# This file holds only Mathesis's data and hooks: its claims, the input set and
# invocation of each prover, the Agda trusted base, and where the proof-status
# file records the claim ids and the reconciled legs. The runs are in the run
# ledger, verification/receipts/theory_runs.ledger, one row a run and prover.
# The receipt (verification/receipts/theory_praxis.deed) is generated from them:
# nothing in it is typed, the grade least of all.
#
#   bash scripts/grade-receipt.sh --check     regenerate, refuse a difference,
#                                             run the §8.5.3 git checks and the
#                                             pinned reader (just receipt-check)
#   bash scripts/grade-receipt.sh --write     write the receipt from the ledger
#   bash scripts/grade-receipt.sh --run-row PROVER --run URL --commit SHA \
#        --checker TEXT --reported TEXT --axioms none
#                                             print one ledger row for a run
#                                             that just passed (the gate job)
#   bash scripts/grade-receipt.sh --record ROWS
#                                             check ROWS, write the receipt and
#                                             append them to the ledger
#
# MATHESIS_STANDARDS names a checkout of metadatastician/standards at the
# commit that scripts/registry/claims-registry.mjs pins; that script checks the
# SHA-256 of the four files the generator needs before this one sources them.
# The RECEIPT_* variables are read by the generator sourced at the end, whose
# path (the pinned standards checkout) a static check cannot follow.
# shellcheck disable=SC2034
set -euo pipefail
cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.."
export LC_ALL=C.UTF-8

RECEIPT_STD="$(bun scripts/registry/claims-registry.mjs standards)" \
  || { echo "ERROR: the standards checkout (MATHESIS_STANDARDS) is not at the pinned commit" >&2; exit 2; }
RECEIPT_STANDARDS_COMMIT="$(bun -e 'import {READER} from "./scripts/registry/claims-registry.mjs"; console.log(READER.commit)')"
RECEIPT_OUT=verification/receipts/theory_praxis.deed
RECEIPT_LEDGER=verification/receipts/theory_runs.ledger
RECEIPT_REPOSITORY=hyperpolymath/mathesis
RECEIPT_DEFAULT_BRANCH=main
RECEIPT_CANONICAL_NAME=mathesis-theory-receipt
RECEIPT_BEHOLDING_CHORA='#u8"chora:estate/github.com/hyperpolymath"'
RECEIPT_SCRIPT=scripts/grade-receipt.sh
# A receipt that is not current keeps what its run read: its inputs digest and
# axioms from the ledger row, and its inputs manifest when that can be rebuilt to
# the same digest (PROOF-POLICY §8.5.1; owner ruling 2026-11-24). None of it
# counts toward a grade. Set here, it is the same for --write and --check.
RECEIPT_KEEP_LINEAGE_DETAIL=1

AGDA=verification/proofs/agda
COQ=verification/proofs/coq
LEAN=verification/proofs/lean4
# The graded Agda roots: THY-1 (FeatureReachability), APP-1 and APP-4
# (Applied.Missing), APP-2 and APP-3 (Applied.Cash, through Applied.IntLaws,
# which proves the integer instance and imports Cash).
AGDA_ROOTS=("$AGDA/FeatureReachability.agda" "$AGDA/Applied/Missing.agda" "$AGDA/Applied/IntLaws.agda")

# id | §5 token of the Agda proof | kind | Rocq route | Rocq §2.2 state |
# Lean route | Lean §2.2 state | Rocq reason | Lean reason
receipt_claims() {
  local id
  for id in THY-1 APP-1 APP-2 APP-3 APP-4; do
    printf '%s|proven|theorem|re-proved|RECONCILED|re-proved|RECONCILED||\n' "$id"
  done
}

# The runs before 2026-11-10 were local, and the run of 2026-11-10 was on
# THY-1 alone: their receipts belong to THY-1 only (APP-1 to APP-4 came later).
receipt_run_scope() {
  local p
  for p in agda rocq lean; do
    printf '%s|local run, 2026-11-09|THY-1\n' "$p"
    printf '%s|https://github.com/hyperpolymath/mathesis/actions/runs/42896264290/job/130110238086|THY-1\n' "$p"
  done
}

receipt_echoes() { :; }

receipt_header() {
  cat <<'EOF'
;; SPDX-License-Identifier: CC-BY-SA-4.0
;; SPDX-FileCopyrightText: 2026 Jonathan D.A. Jewell (hyperpolymath)
;; The proof receipt of Mathesis (PROOF-POLICY §8.5.1), for THY-1 and APP-1 to
;; APP-4 in docs/status/PROOF-STATUS.adoc. GENERATED by scripts/grade-receipt.sh
;; with the shared generator of standards (scripts/proof-receipt.sh, at the
;; commit scripts/registry/claims-registry.mjs pins) from the run ledger
;; verification/receipts/theory_runs.ledger; do not hand-edit. Each run of the
;; proof lanes in the pinned Guix shell is one row a prover; its current
;; receipt carries the inputs manifest of that prover and the axioms the run
;; reported (none). No row names a container image pinned by digest, so no
;; claim is PWG-1 (§8.2, standards#1625): the generator and the reader derive
;; PWG-2ii. Earlier receipts stay as superseded receipts, each with a reason.
;; The trusted base is each prover-supplied postulate that the Agda import
;; cones reach (agda --dependency-graph): the four of Agda.Primitive, and Char
;; and String, which Applied/IntLaws reaches through Agda.Builtin.Int. Agda
;; 2.7.0.1 postulates these six (its lib/prim sources, read 2026-11-13).
EOF
}

receipt_trusted_base() {
  printf '%s\n' \
    'Agda.Primitive|Level|BUILTIN LEVEL' \
    'Agda.Primitive|lzero|BUILTIN LEVELZERO' \
    'Agda.Primitive|lsuc|BUILTIN LEVELSUC' \
    'Agda.Primitive|_⊔_|BUILTIN LEVELMAX' \
    'Agda.Builtin.Char|Char|BUILTIN CHAR' \
    'Agda.Builtin.String|String|BUILTIN STRING'
}

# What each lane of the Proof Policy Gate runs (.github/workflows/agda-proof-policy.yml),
# in the pinned Guix shell.
receipt_invocation() {
  case "$1" in
    agda) printf 'bash scripts/check-proofs.sh agda: agda --safe --without-K --cubical-compatible on each gated module of %s\n' "$AGDA" ;;
    rocq) printf 'bash scripts/check-proofs.sh coq: coqc, Print Assumptions and coqchk -o on each gated module of %s\n' "$COQ" ;;
    lean) printf 'bash scripts/check-proofs.sh lean4: lean and the axiom audit on each gated module of %s\n' "$LEAN" ;;
  esac
}

# The gated modules of a prover, from its MANIFEST (dir|module|gated|note).
gated() { awk -F'|' '!/^[[:space:]]*#/ && $3=="gated"{print $1 "/" $2}' "$1/MANIFEST"; }

# §8.5.1 input sets. Agda: the first-party cone of the graded roots. Rocq: each
# file the gate compiles. Lean: each file the gate checks, and lean-toolchain.
receipt_inputs() {
  local r
  case "$1" in
    agda) for r in "${AGDA_ROOTS[@]}"; do receipt_agda_cone "$r" "$AGDA"; done ;;
    rocq) gated "$COQ" ;;
    lean) gated "$LEAN"; printf '%s/lean-toolchain\n' "$LEAN" ;;
  esac
}

# The claim ids of the proof-status file: those its "===" headings name, with
# a range such as "APP-1 to APP-4" written out.
status_sections() {
  awk '
    function ids(h,   out, a, b, p, n, i) {
      out = ""
      while (match(h, /[A-Z]+-[0-9]+( to [A-Z]+-[0-9]+)?/)) {
        p = substr(h, RSTART, RLENGTH); h = substr(h, RSTART + RLENGTH)
        if (p ~ / to /) {
          split(p, a, / to /); n = a[1]; sub(/-[0-9]+$/, "", n)
          for (i = substr(a[1], length(n) + 2) + 0; i <= substr(a[2], length(n) + 2) + 0; i++) out = out " " n "-" i
        } else out = out " " p
      }
      return out
    }
    function flush() { if (cur != "") print cur "|" rec "|" both }
    /^=== / { flush(); h = $0; sub(/:.*/, "", h); cur = ids(h); rec = 0; both = 0; next }
    /^== / { flush(); cur = ""; next }
    cur != "" && /correspondence `RECONCILED`/ { rec++ }
    cur != "" && /Rocq and Lean legs are `RECONCILED`/ { both = 1 }
    END { flush() }
  ' docs/status/PROOF-STATUS.adoc
}
receipt_status_ids() { status_sections | cut -d'|' -f1 | tr ' ' '\n' | grep . || true; }
# A claim's legs are recorded as RECONCILED when its section says so of the
# Rocq and the Lean leg: two "correspondence `RECONCILED`" rows, or one sentence
# for both.
receipt_recorded_legs() {
  status_sections | awk -F'|' '$2 >= 2 || $3 == 1 {print $1}' | tr ' ' '\n' | grep . || true
}

# shellcheck source=/dev/null
. "$RECEIPT_STD/scripts/proof-receipt.sh"
receipt_main "$@"
