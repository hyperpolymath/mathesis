// The theory shelf of Mathesis (re-anchoring plan WO 4.1).
//
// docs/theory/admissions.jsonl holds one authored admission record for each
// theorem whose home is Mathesis. A theorem enters the shelf only when the
// admission rule of docs/theory/README.adoc holds: it is theory by the test of
// PROOF-POLICY §1, no single system owns it, and an estate rule, vocabulary or
// interface depends on it. The record states each condition and names the
// dependant. It holds no grade: claims-registry.mjs derives the grade from the
// receipt and renders docs/theory/generated/index.adoc from both.

export const HOME = 'hyperpolymath/mathesis';
// A home theorem is on the theory shelf or on the applied shelf (owner ruling
// 2026-11-12). Only the theory shelf needs an admission.
export const onTheoryShelf = r => r.repo === HOME && r.kind === 'theorem' && r.shelf === 'theory';
const FIELDS = new Set(['id', 'admitted', 'theory', 'owner', 'dependant']);
const DEPENDANT_FIELDS = new Set(['repository', 'path', 'rule']);

const text = v => typeof v === 'string' && v.trim() !== '';

// Throw `message` unless `ok`.
const need = (ok, message) => {
  if (!ok) throw new Error(message);
};

// Throw unless every admission is well formed, names a public dependant, and
// matches one theory-shelf pin; and unless every theory-shelf pin has one
// admission. `rows` are the validated claim pins.
export function validateAdmissions(admissions, rows, inventory) {
  need(Array.isArray(admissions), 'docs/theory/admissions.jsonl must hold one admission record on each line');
  const visibility = new Map(inventory.map(r => [r.full_name, r.visibility]));
  const home = new Map(rows.filter(onTheoryShelf).map(r => [r.id, r]));
  const seen = new Set();
  admissions.forEach((a, i) => {
    const where = `admission ${i + 1}`;
    for (const k of Object.keys(a)) need(FIELDS.has(k), `Unknown field (an admission holds no grade) ${k}: ${where}`);
    need(home.has(a.id), `No theory-shelf pin for ${a.id}: ${where}`);
    need(!seen.has(a.id), `Duplicate admission ${a.id}`);
    seen.add(a.id);
    need(typeof a.admitted === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(a.admitted), `admitted is a date: ${a.id}`);
    need(text(a.theory), `Missing theory test: ${a.id}`);
    need(text(a.owner), `Missing owner test: ${a.id}`);
    const d = a.dependant;
    need(d !== null && typeof d === 'object', `Missing dependant: ${a.id}`);
    for (const k of Object.keys(d)) need(DEPENDANT_FIELDS.has(k), `Unknown dependant field ${k}: ${a.id}`);
    need(visibility.get(d.repository) === 'public', `Nonpublic or unlisted dependant repository: ${a.id}`);
    need(text(d.path) && text(d.rule), `The dependant names a path and a rule: ${a.id}`);
  });
  for (const id of home.keys()) need(seen.has(id), `Theory-shelf theorem ${id} has no admission record`);
  return admissions;
}

const cell = s => String(s).replaceAll('|', String.raw`\|`).replaceAll('\n', ' ');

// Render the theorem index from the derived registry rows of the home
// theorems and their admissions.
export function renderTheoryIndex(derived, admissions) {
  const byId = new Map(admissions.map(a => [a.id, a]));
  const home = derived.filter(d => onTheoryShelf(d.row))
    .sort((a, b) => a.row.claim.localeCompare(b.row.claim, 'en', {numeric: true}));
  const out = [
    '// SPDX-License-Identifier: CC-BY-SA-4.0',
    '// GENERATED by scripts/registry/claims-registry.mjs from docs/theory/admissions.jsonl,',
    '// docs/atlas/claims/claims.jsonl and the receipt they pin; do not hand-edit.',
    '= Theorem index of the theory shelf',
    '',
    'One row for each theorem whose home is Mathesis. The grade is derived from',
    'the receipt by the canon reader, never typed. The admission rule is in',
    'link:../README.adoc[the theory README].',
    '',
    `Theorems: ${home.length}.`,
    '',
    '[cols="1,3,1,2,3",options="header"]',
    '|===',
    '|Theorem |Statement |PWG |Source and receipt |Dependant',
    '',
  ];
  for (const d of home) {
    const r = d.row;
    const a = byId.get(r.id);
    const names = r.agda ? `\`${cell(r.agda.module)}\`: ${r.agda.names.map(n => '`' + cell(n) + '`').join(', ')}` : '-';
    const receipt = r.receipt ? `\`${cell(r.receipt.path)}\` at \`${r.source_commit.slice(0, 12)}\`` : 'no receipt';
    const dep = `https://github.com/${a.dependant.repository}/blob/main/${a.dependant.path}[${cell(a.dependant.repository)}]: ${cell(a.dependant.rule)}`;
    out.push(`|${r.claim} |${cell(r.statement)} |\`${d.pwg}\` |${names}; ${receipt} |${dep}`, '');
  }
  out.push('|===', '');
  return out.join('\n');
}
