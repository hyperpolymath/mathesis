import {test, expect} from 'bun:test';
import {readFileSync} from 'node:fs';
import {VIEWS, frontPage, checkLinks, htmlPath, GITHUB} from '../../scripts/site/site.mjs';

const root = new URL('../../', import.meta.url).pathname;
const read = f => readFileSync(root + f, 'utf8');

test('the front page links every view and says how each is derived', () => {
  const page = frontPage(read);
  for (const v of VIEWS) {
    expect(page).toContain(`link:${htmlPath(v.file)}[`);
    expect(page).toContain(v.how);
  }
  expect(page).toContain('GENERATED by scripts/site/site.mjs');
});

test('the front page fails when a view header no longer names its source', () => {
  const bad = f => read(f).replaceAll('claims-registry.mjs', 'x').replaceAll('census/rows.jsonl', 'x');
  expect(() => frontPage(bad)).toThrow(/header does not name/);
});

const none = () => new Set();
const run = (html, site, repo, page = 'docs/a/x.html', ids = none) =>
  checkLinks(page, html, p => site.includes(p), p => repo.includes(p), ids);

test('a link to another page of the site becomes an .html link', () => {
  const r = run('<a href="y.adoc">y</a>', ['docs/a/y.html'], []);
  expect(r.errors).toEqual([]);
  expect(r.html).toBe('<a href="y.html">y</a>');
});

test('a link to a repository file outside the site becomes a GitHub link at main', () => {
  const r = run('<a href="../README.adoc#top">r</a>', [], ['docs/README.adoc']);
  expect(r.errors).toEqual([]);
  expect(r.html).toBe(`<a href="${GITHUB}/blob/main/docs/README.adoc#top">r</a>`);
});

test('a link to a file that exists nowhere fails', () => {
  expect(run('<a href="gone.adoc">g</a>', [], []).errors[0]).toMatch(/broken relative link/);
});

test('a link that leaves the repository fails', () => {
  expect(run('<a href="../../../x">g</a>', [], [], 'a/x.html').errors[0]).toMatch(/leaves the repository/);
});

test('a missing anchor fails, and absolute and in-page links pass', () => {
  expect(run('<a href="y.html#nope">y</a>', ['docs/a/y.html'], []).errors[0]).toMatch(/no anchor/);
  const ids = () => new Set(['top']);
  expect(run('<a href="#top">t</a><a href="https://example.org/x">e</a>', [], [], 'docs/a/x.html', ids).errors).toEqual([]);
});
